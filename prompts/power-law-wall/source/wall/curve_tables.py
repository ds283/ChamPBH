"""
power-law-wall prompt 02 §1.6: stage2_scan.txt's curve points as Markdown tables, one per curve, with the adopted law's
fraction beside stage 2's at L_E = ln(1 + x) and at L = n (powerscan.f_law, drain_fraction term for term; in the
classical regime f_law reads the exponential's S table at that L).

    cd prompts/power-law-wall/source/wall && ../../../../venv/bin/python curve_tables.py \
        > ../../../../.documents/power-law-wall/wall-02/stage2_curves.md
"""

import os
import sys
from math import exp, log1p

sys.path.insert(0, ".")
import powerscan as ps  # noqa: E402

HERE = os.path.dirname(os.path.abspath(__file__))
print(
    "# stage 2 along the curves (scan_curves.py), with the adopted law at L_E and L = n; generated by "
    "curve_tables.py"
)
cur = None
for line in open(
    os.path.join(HERE, "../../../../.documents/power-law-wall/wall-02/stage2_scan.txt")
):
    f = line.split()
    if not f or not f[0].startswith("curve-"):
        continue
    if f[0] != cur:
        cur = f[0]
        print(f"\n**{cur}**\n")
        print(
            "| ln R | ln x | regime | ℓ | ℓ_∞ | | f (modes) | f (balance) | v_out/v_in | back | ε_turn | \\|ΔE/E\\| | s | law L_E | law L = n |"
        )
        print("|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|")
    n = int(f[1])
    lnR = float(f[2])
    lnx = float(f[3])
    reg = f[5]
    ell = None if f[6] == "none" else float(f[6])
    LE = log1p(exp(lnx))
    lE = ps.f_law(reg, ell, LE, lnR)
    ln_ = ps.f_law(reg, ell, float(n), lnR)
    print(
        f"| {lnR:.3f} | {lnx:.3f} | {reg} | {f[6]} | {f[7]} | {f[8]} | {float(f[9]):.4g} | {float(f[10]):.4g} | {f[11]} | {f[12]} | {f[13]} | {f[14]} | {f[16]} | {lE:.4g} | {ln_:.4g} |"
    )
