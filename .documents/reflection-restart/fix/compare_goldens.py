"""
The golden records of reflection-restart prompt 03 (§1.6; orchestrator note 03, ruling 3), field by field:
each record regenerated by this prompt against the record of everything before it.

    data/golden_history_05.json        -> data/golden_history_rr03.json         (beta = 1.5 and 5.5)
    data/golden_history_06_tuned.json  -> data/golden_history_rr03_tuned.json   (beta = 3, M = 0.01, tuned)

Every top-level key of each history record (record_of's), every excerpt field by field, and (tuned) every
tuning key is compared exactly, as text. Exactly two differences are allowed (ruling 3): the value of
`solver_label` ("Radau+kinematic-cap-stepping0" -> "Radau+kinematic-cap-stepping1") and the key
`restart_retakes`, added by this prompt, which must be 0. Anything else is listed as a difference, and the
script ends "RESULT: DIFFERENT". The provenance blocks are not compared (they name the commit, the time and the
wall-clock of the generation).

    PYTHONPATH=. ./venv/bin/python .documents/reflection-restart/fix/compare_goldens.py \\
        > .documents/reflection-restart/fix/out/compare_goldens.txt

Reads only; runs nothing.
"""

import json
import sys
from pathlib import Path

DATA = Path("ComputeTargets/tests/data")
PAIRS = (
    ("golden_history_05.json", "golden_history_rr03.json", "histories"),
    ("golden_history_06_tuned.json", "golden_history_rr03_tuned.json", "tuned"),
)
OLD_LABEL = "Radau+kinematic-cap-stepping0"
NEW_LABEL = "Radau+kinematic-cap-stepping1"


def compare_history(name: str, old: dict, new: dict, out: list) -> int:
    """One history record; returns the number of differences that are not allowed."""
    bad = 0
    for key in sorted(set(old) | set(new)):
        if key == "excerpts":
            continue
        if key not in old:
            if key == "restart_retakes" and new[key] == 0:
                out.append(f"  {name}: {key}: added, {new[key]!r} (allowed)")
            else:
                out.append(f"  {name}: {key}: added, {new[key]!r} -- DIFFERENCE")
                bad += 1
            continue
        if key not in new:
            out.append(f"  {name}: {key}: missing in the new record -- DIFFERENCE")
            bad += 1
            continue
        if old[key] == new[key]:
            out.append(f"  {name}: {key}: equal")
        elif key == "solver_label" and (old[key], new[key]) == (OLD_LABEL, NEW_LABEL):
            out.append(f"  {name}: {key}: {old[key]!r} -> {new[key]!r} (allowed)")
        else:
            out.append(f"  {name}: {key}: {old[key]!r} -> {new[key]!r} -- DIFFERENCE")
            bad += 1

    old_ex = {e["index"]: e for e in old["excerpts"]}
    new_ex = {e["index"]: e for e in new["excerpts"]}
    if sorted(old_ex) != sorted(new_ex):
        out.append(f"  {name}: excerpts: the indices differ -- DIFFERENCE")
        bad += 1
    fields = 0
    for index in sorted(set(old_ex) & set(new_ex)):
        o, n = old_ex[index], new_ex[index]
        if o["log_one_plus_z"] != n["log_one_plus_z"]:
            out.append(f"  {name}: excerpt {index}: log_one_plus_z -- DIFFERENCE")
            bad += 1
        for field in sorted(set(o["fields"]) | set(n["fields"])):
            fields += 1
            if o["fields"].get(field) != n["fields"].get(field):
                out.append(
                    f"  {name}: excerpt {index}: {field}: {o['fields'].get(field)} -> "
                    f"{n['fields'].get(field)} -- DIFFERENCE"
                )
                bad += 1
    out.append(
        f"  {name}: excerpts: {len(old_ex)} samples, {fields} fields, "
        + ("all equal" if bad == 0 else "see above")
    )
    return bad


def main() -> int:
    out = []
    bad = 0
    for old_name, new_name, kind in PAIRS:
        old = json.loads((DATA / old_name).read_text())
        new = json.loads((DATA / new_name).read_text())
        out.append(f"{old_name} -> {new_name}")
        if kind == "histories":
            if sorted(old["histories"]) != sorted(new["histories"]):
                out.append("  the histories differ -- DIFFERENCE")
                bad += 1
            for key in sorted(old["histories"]):
                bad += compare_history(
                    key, old["histories"][key], new["histories"][key], out
                )
        else:
            bad += compare_history("history", old["history"], new["history"], out)
            for key in sorted(set(old["tuning"]) | set(new["tuning"])):
                if old["tuning"].get(key) == new["tuning"].get(key):
                    out.append(f"  tuning: {key}: equal")
                else:
                    out.append(
                        f"  tuning: {key}: {old['tuning'].get(key)!r} -> "
                        f"{new['tuning'].get(key)!r} -- DIFFERENCE"
                    )
                    bad += 1
        out.append("")
    out.append(f"differences not allowed: {bad}")
    out.append(
        "RESULT: " + ("EQUAL but for the two allowed" if bad == 0 else "DIFFERENT")
    )
    print("\n".join(out))
    return 0 if bad == 0 else 1


if __name__ == "__main__":
    sys.exit(main())
