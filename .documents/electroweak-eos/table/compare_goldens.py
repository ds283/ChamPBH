"""
The golden records of electroweak-eos prompt 01 (§1.7; orchestrator note 01, ruling 4), field by field: each
record regenerated by this prompt, on the new w table, against the record of everything before it.

    data/golden_history_rr03.json             -> data/golden_history_ee01.json             (beta = 1.5 and 5.5)
    data/golden_history_rr03_tuned.json       -> data/golden_history_ee01_tuned.json       (beta = 3, M = 0.01, tuned)
    data/golden_history_rr03_reflecting.json  -> data/golden_history_ee01_reflecting.json  (beta = 1.5, M = 1e-12,
                                                                                            alpha = 0.05, tuned)

Every value is expected to move: every golden history starts at T* = 2e4 GeV and crosses the electroweak
scale, where the table changed. So the script does not look for equality. It states, per history, old and
new: the reflections, accepted steps and RHS evaluations; the first bounce (N, phi_E, ln T_J); the
fixed-temperature values; for the tuned records the tuned normalization and phi_ref (and every other tuning
key); and the final sample's fields (the last excerpt, which record_of takes at the history's last sample).

What may not change is the form (the prompt's §1.7; a change there is a stop): the records' keys at every
level, `solver_label`, `sample_fields`, and the sampling axis's length (`n_samples`) and its points'
labels (the excerpts' indices and their ln(1 + z), which the axis fixes). Each is checked, and the script ends
"FORM: SAME" or "FORM: CHANGED". The provenance blocks are not compared.

    PYTHONPATH=. ./venv/bin/python .documents/electroweak-eos/table/compare_goldens.py \\
        > .documents/electroweak-eos/table/out/compare_goldens.txt

Reads only; runs nothing.
"""

import json
import sys
from pathlib import Path

DATA = Path("ComputeTargets/tests/data")
PAIRS = (
    ("golden_history_rr03.json", "golden_history_ee01.json", "histories"),
    ("golden_history_rr03_tuned.json", "golden_history_ee01_tuned.json", "tuned"),
    (
        "golden_history_rr03_reflecting.json",
        "golden_history_ee01_reflecting.json",
        "tuned",
    ),
)
COUNTS = (
    "reflections",
    "accepted_steps",
    "RHS_evaluations",
    "compute_steps",
    "steps_rejected_by_exception",
    "restart_retakes",
)
FORM_EQUAL = ("solver_label", "sample_fields", "n_samples")


def _f(x):
    """A record's value as a number where it is a float.hex string, else as it is."""
    if isinstance(x, str) and x.startswith(("0x", "-0x")):
        return float.fromhex(x)
    return x


def _show(x):
    x = _f(x)
    return f"{x:.10g}" if isinstance(x, float) else repr(x)


def _row(label, old, new, out):
    o, n = _f(old), _f(new)
    note = ""
    if isinstance(o, float) and isinstance(n, float) and o != 0.0:
        note = f"   (rel {n / o - 1.0:+.3e})"
    elif isinstance(o, int) and isinstance(n, int) and not isinstance(o, bool):
        note = f"   ({n - o:+d})"
    same = " (equal)" if old == new else ""
    out.append(f"    {label:<34}{_show(old):>22} -> {_show(new):<22}{note}{same}")


def compare_history(name: str, old: dict, new: dict, out: list) -> int:
    """One history record; returns the number of changes of form."""
    bad = 0
    out.append(f"  {name}")
    if sorted(old) != sorted(new):
        out.append(f"    keys: {sorted(set(old) ^ set(new))} differ -- FORM CHANGED")
        bad += 1
    for key in FORM_EQUAL:
        if old.get(key) != new.get(key):
            out.append(
                f"    {key}: {old.get(key)!r} -> {new.get(key)!r} -- FORM CHANGED"
            )
            bad += 1
        else:
            out.append(f"    {key}: {old.get(key)!r} (same)")

    out.append("    counts")
    for key in COUNTS:
        _row(key, old.get(key), new.get(key), out)

    out.append("    first bounce")
    ob, nb = old.get("first_bounce"), new.get("first_bounce")
    if (ob is None) != (nb is None):
        out.append(f"    first_bounce: {ob!r} -> {nb!r}")
    elif ob is not None:
        if sorted(ob) != sorted(nb):
            out.append("    first_bounce keys differ -- FORM CHANGED")
            bad += 1
        for key in ("N", "phi_Einstein", "log_T_Jordan", "reflected"):
            _row(key, ob.get(key), nb.get(key), out)

    out.append("    fixed-temperature values")
    of, nf = old.get("fixed_T_values") or {}, new.get("fixed_T_values") or {}
    if sorted(of) != sorted(nf):
        out.append("    fixed_T_values keys differ -- FORM CHANGED")
        bad += 1
    for key in sorted(of):
        _row(key, of.get(key), nf.get(key), out)

    out.append("    step control")
    for key in (
        "cap_fraction",
        "cap_floor",
        "cap_global_max_step",
        "jacobian_factor_max",
    ):
        _row(key, old.get(key), new.get(key), out)

    out.append("    hashes")
    for key in ("samples_sha256", "log_one_plus_z_sha256"):
        out.append(
            f"    {key:<34}{'equal' if old.get(key) == new.get(key) else 'differs'}"
        )

    old_ex = {e["index"]: e for e in old["excerpts"]}
    new_ex = {e["index"]: e for e in new["excerpts"]}
    if sorted(old_ex) != sorted(new_ex):
        out.append("    excerpts: the indices differ -- FORM CHANGED")
        bad += 1
    else:
        labels = sum(
            1
            for i in old_ex
            if old_ex[i]["log_one_plus_z"] != new_ex[i]["log_one_plus_z"]
        )
        if labels:
            out.append(
                f"    excerpts: {labels} points' ln(1 + z) differ -- FORM CHANGED"
            )
            bad += 1
        changed = sum(
            1
            for i in old_ex
            for f in old_ex[i]["fields"]
            if old_ex[i]["fields"][f] != new_ex[i]["fields"].get(f)
        )
        total = sum(len(old_ex[i]["fields"]) for i in old_ex)
        out.append(
            f"    excerpts: {len(old_ex)} samples at the same indices and ln(1 + z); "
            f"{changed} of {total} field values changed"
        )
        last = max(old_ex)
        out.append(
            f"    the final sample (index {last}, ln(1 + z) = {_show(old_ex[last]['log_one_plus_z'])})"
        )
        for f in old_ex[last]["fields"]:
            _row(f, old_ex[last]["fields"][f], new_ex[last]["fields"].get(f), out)
    return bad


def main() -> int:
    out = []
    bad = 0
    for old_name, new_name, kind in PAIRS:
        old = json.loads((DATA / old_name).read_text())
        new = json.loads((DATA / new_name).read_text())
        out.append(f"{old_name} -> {new_name}")
        top = sorted(set(old) - {"provenance"}), sorted(set(new) - {"provenance"})
        if top[0] != top[1]:
            out.append(f"  top-level keys {top[0]} -> {top[1]} -- FORM CHANGED")
            bad += 1
        if kind == "histories":
            if sorted(old["histories"]) != sorted(new["histories"]):
                out.append("  the histories differ -- FORM CHANGED")
                bad += 1
            for key in sorted(old["histories"]):
                bad += compare_history(
                    key, old["histories"][key], new["histories"][key], out
                )
        else:
            bad += compare_history("history", old["history"], new["history"], out)
            out.append("  tuning")
            if sorted(old["tuning"]) != sorted(new["tuning"]):
                out.append("    tuning keys differ -- FORM CHANGED")
                bad += 1
            for key in ("normalization", "phi_ref"):
                _row(key, old["tuning"].get(key), new["tuning"].get(key), out)
            for key in sorted(set(old["tuning"]) - {"normalization", "phi_ref"}):
                _row(key, old["tuning"].get(key), new["tuning"].get(key), out)
            if "reflecting" in old or "reflecting" in new:
                out.append("  reflecting")
                o, n = old.get("reflecting", {}), new.get("reflecting", {})
                if sorted(o) != sorted(n):
                    out.append("    reflecting keys differ -- FORM CHANGED")
                    bad += 1
                for key in sorted(o):
                    _row(key, o.get(key), n.get(key), out)
        out.append("")
    out.append(f"changes of form: {bad}")
    out.append("FORM: " + ("SAME" if bad == 0 else "CHANGED"))
    print("\n".join(out))
    return 0 if bad == 0 else 1


if __name__ == "__main__":
    sys.exit(main())
